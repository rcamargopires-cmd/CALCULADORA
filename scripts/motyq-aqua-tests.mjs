assert.ok(!src.includes('fetch(')&&!ui.includes('window.open('));
const aqua=await import('data:text/javascript;base64,'+Buffer.from(transpile(src)).toString('base64'));
const start='2026-11-12T12:00:00.000Z';
const v={brand:'Jeep',model:'Renegade',year:'2022',km:'45000',vehicleType:'car',notes:'Boa conservação'};
const source={...v,plate:'ABC1D23',fipe:98000,cost:1500};
const pub=aqua.publicAquaVehicle(source,'Boa conservação');
assert.equal('plate' in pub,false);assert.equal('fipe' in pub,false);assert.equal('cost' in pub,false);
const open=aqua.createAquaLot({vehicle:pub,mode:'open',endsAt:'2026-11-14T12:00:00Z',visibleBuyerIds:['a','b'],minimumIncrement:500},start);
assert.equal(open.mode,'open');assert.equal(open.state,'open');
assert.throws(()=>aqua.simulateAquaBid(open,{id:'c',shop:'Não convidado'},70000,'2026-11-13T12:00:00Z'),/não convidado/);
const first=aqua.simulateAquaBid(open,{id:'a',shop:'Loja A'},70000,'2026-11-13T12:00:00Z');
assert.throws(()=>aqua.simulateAquaBid(first,{id:'b',shop:'Loja B'},70200,'2026-11-13T12:01:00Z'),/incremento/);
const second=aqua.simulateAquaBid(first,{id:'b',shop:'Loja B'},70500,'2026-11-13T12:02:00Z');
assert.equal(aqua.highestAquaBid(second).amount,70500);
assert.equal(aqua.visibleAquaBidSummary(second,'a').highest,70500);
assert.equal(aqua.visibleAquaBidSummary(second,'outsider'),null);
const sealed=aqua.createAquaLot({vehicle:pub,mode:'sealed',endsAt:'2026-11-14T12:00:00Z',visibleBuyerIds:['a','b']},start);
const s1=aqua.simulateAquaBid(sealed,{id:'a',shop:'Loja A'},70000,'2026-11-13T12:00:00Z');
const s2=aqua.simulateAquaBid(s1,{id:'b',shop:'Loja B'},65000,'2026-11-13T12:01:00Z');
assert.equal(aqua.visibleAquaBidSummary(s2,'a').highest,null);
assert.equal(aqua.visibleAquaBidSummary(s2,'a').ownBids.length,1);
assert.equal(aqua.visibleAquaBidSummary(s2,'a').bidCount,null);
assert.throws(()=>aqua.simulateAquaBid(s2,{id:'a',shop:'Loja A'},71000,'2026-11-14T12:00:00Z'),/encerrada/);
assert.throws(()=>aqua.createAquaLot({vehicle:pub,mode:'open',endsAt:'2026-11-11T12:00:00Z',visibleBuyerIds:['a']},start),/encerramento/);
assert.throws(()=>aqua.createAquaLot({vehicle:pub,mode:'open',endsAt:'2026-11-14T12:00:00Z',visibleBuyerIds:[]},start),/lojista/);
const closed=aqua.closeAquaLot(second,'2026-11-13T13:00:00Z');
assert.throws(()=>aqua.simulateAquaBid(closed,{id:'a',shop:'Loja A'},72000,'2026-11-13T13:01:00Z'),/encerrada/);
