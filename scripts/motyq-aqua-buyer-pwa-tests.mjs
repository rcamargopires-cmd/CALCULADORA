import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const tsOptions={target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext,jsx:ts.JsxEmit.ReactJSX};
const transpile=s=>{const r=ts.transpileModule(s,{compilerOptions:tsOptions,reportDiagnostics:true});
 assert.equal((r.diagnostics||[]).filter(x=>x.category===ts.DiagnosticCategory.Error).length,0);
 return r.outputText;};
const service=readFileSync('services/motyqAquaBuyerPreview.ts','utf8');
const panel=readFileSync('components/MarketIqAquaBuyerMobile.tsx','utf8');
const entry=readFileSync('index.tsx','utf8');
const html=readFileSync('index.html','utf8');
const vercel=JSON.parse(readFileSync('vercel.json','utf8'));
const manifest=JSON.parse(readFileSync('public/aqua-lojista.webmanifest','utf8'));
transpile(panel);
const m=await import('data:text/javascript;base64,'+Buffer.from(transpile(service)).toString('base64'));
const vehicles=m.sampleBuyerLots(Date.parse('2026-11-13T12:00:00Z'));
const prefs=m.defaultAquaInterest();
assert.equal(m.buyerListingMatches(vehicles[0],prefs),true);
assert.equal(m.buyerListingMatches(vehicles[1],prefs),true);
assert.equal(m.buyerListingMatches(vehicles[2],prefs),false);
assert.equal(m.findNewRelevantListings([vehicles[0].id],vehicles,prefs).length,1);
assert.equal(m.findNewRelevantListings(vehicles.map(x=>x.id),vehicles,prefs).length,0);
assert.equal(m.buyerListingMatches(vehicles[0],{...prefs,maxKm:'10000'}),false);
assert.equal(m.buyerListingMatches(vehicles[0],{...prefs,yearFrom:'2024'}),false);
assert.equal(m.buyerListingMatches(vehicles[0],{...prefs,brands:'Fiat'}),false);
assert.equal(m.buyerListingMatches(vehicles[0],{...prefs,budgetTo:'90000'}),false);
assert.equal(m.buyerListingMatches(vehicles[1],{...prefs,models:'T-Cross'}),true);
const store=new Map();
globalThis.localStorage={getItem:k=>store.get(k)||null,setItem:(k,v)=>store.set(k,v)};
m.saveAquaInterest({...prefs,brands:'Fiat'});
assert.equal(m.loadAquaInterest().brands,'Fiat');
assert.ok(!panel.includes('loadAquaLots('),'Never expose Mesa local lots through public buyer route');
assert.ok(!panel.includes('db.')&&!panel.includes('onSnapshot('),'No unauthenticated access to Firestore');
assert.ok(panel.includes('Notification.requestPermission()'),'Permission must require buyer action');
assert.ok(panel.includes('navigator.serviceWorker.ready')&&panel.includes('reg.showNotification('));
assert.ok(readFileSync('public/motyq-iq-sw.js','utf8').includes("self.clients.openWindow('/aqua/lojista')"));
assert.ok(panel.includes('Simular carro novo'));
assert.ok(panel.includes('Ainda não existe login')||panel.includes('após autenticação'),'Must label demo');
assert.ok(panel.includes('Notificações em segundo plano virão com o serviço de push.'));
assert.ok(panel.includes('Instalar'));
assert.ok(entry.includes("==='/aqua/lojista'?<MarketIqAquaBuyerConnected/>"));
assert.ok(vercel.rewrites.some(r=>r.source==='/aqua/lojista'&&r.destination==='/index.html'));
assert.equal(manifest.display,'standalone');
assert.equal(manifest.start_url,'/aqua/lojista');
assert.equal(manifest.scope,'/aqua/');
assert.notEqual(manifest.id,'/motyq-iq');
assert.ok(html.includes('/aqua-lojista.webmanifest'));
assert.ok(manifest.icons.some(x=>x.sizes==='192x192'));
console.log('Motyq AQUA Lojista PWA: separate install manifest, safe demo route, match preferences, foreground alert and privacy guards passed.');
