import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const ui=readFileSync('components/ManualPricingWorkspace.tsx','utf8');
const i=ui.indexOf('type Ad=');
const j=ui.indexOf('type Saved=',i);
assert.ok(i>=0&&j>i,'Import decoder block exists');
const subset=ui.slice(i,j)+'\nexport {decodeExtensionTransfer};';
const compiled=ts.transpileModule(subset,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext},reportDiagnostics:true});
assert.equal((compiled.diagnostics||[]).filter(x=>x.category===ts.DiagnosticCategory.Error).length,0);
const {decodeExtensionTransfer}=await import('data:text/javascript;base64,'+Buffer.from(compiled.outputText).toString('base64'));
const url='https://www.webmotors.com.br/comprar/fiat/titano/ranch/2025/12345678';
const wrap=(ads,kind='motyq-assisted-v1')=>'#motyq-import='+Buffer.from(JSON.stringify({kind,ads})).toString('base64url');
const valid={title:'Titano Ranch',url,year:2025,km:45000,price:149990};
const received=decodeExtensionTransfer(wrap([valid,valid]));
assert.equal(received.length,1,'Duplicate URL must not duplicate sample');
assert.equal(received[0].status,'pending','Imported quotes must not be pre-approved');
assert.equal(received[0].auto,false,'Captured prices are manual');
assert.equal(decodeExtensionTransfer(wrap([{...valid,url:'https://evil.com/comprar/fiat/titano/ranch/2025/12345678'}])).length,0);
assert.equal(decodeExtensionTransfer(wrap([{...valid,url:'https://www.webmotors.com.br/carros/sp/fiat/titano'}])).length,0);
assert.equal(decodeExtensionTransfer(wrap([{...valid,price:0}])).length,0);
assert.equal(decodeExtensionTransfer(wrap([{...valid,year:1900}])).length,0);
assert.equal(decodeExtensionTransfer(wrap([valid],'unexpected-kind')).length,0);
assert.equal(decodeExtensionTransfer(wrap(Array(13).fill(valid))).length,0);
assert.ok(ui.includes('Adicionar anúncios à comparação'));
assert.ok(ui.includes('Os anúncios importados têm ano diferente do veículo selecionado'));
console.log('MarketIQ assisted extension import: schema, origin, duplicates and pending-state tests passed.');
