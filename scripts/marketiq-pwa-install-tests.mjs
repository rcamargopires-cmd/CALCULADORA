import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createMotyqPng} from './generate-pwa-icons.mjs';
const manifest=JSON.parse(readFileSync('public/motyq-iq.webmanifest','utf8'));
const html=readFileSync('index.html','utf8');
const entry=readFileSync('index.tsx','utf8');
const sw=readFileSync('public/motyq-iq-sw.js','utf8');
const ui=readFileSync('components/MarketIqMobileExperience.tsx','utf8');
const install=readFileSync('services/marketIqPwaInstall.ts','utf8');
const pkg=JSON.parse(readFileSync('package.json','utf8'));
assert.equal(manifest.name,'Motyq IQ Mobile');
assert.equal(manifest.short_name,'Motyq IQ');
assert.equal(manifest.display,'standalone');
assert.equal(manifest.start_url,'/');
assert.equal(manifest.scope,'/');
assert.equal(manifest.prefer_related_applications,false);
assert.equal(manifest.lang,'pt-BR');
assert.ok(manifest.icons.some(i=>i.type==='image/png'&&i.sizes==='192x192'&&i.purpose==='any'));
assert.ok(manifest.icons.some(i=>i.type==='image/png'&&i.sizes==='512x512'&&i.purpose==='any'));
assert.ok(manifest.icons.some(i=>i.type==='image/png'&&i.sizes==='512x512'&&i.purpose==='maskable'));
assert.ok(manifest.icons.every(i=>i.src.startsWith('/')));
for(const size of [192,512]){
 const png=createMotyqPng(size);
 assert.equal(png.subarray(0,8).toString('hex'),'89504e470d0a1a0a');
 assert.equal(png.readUInt32BE(16),size);
 assert.equal(png.readUInt32BE(20),size);
 assert.ok(png.length>1000);
}
const maskable=createMotyqPng(512,{maskable:true});
assert.equal(maskable.readUInt32BE(16),512);
assert.notDeepEqual(maskable,createMotyqPng(512),'Maskable icon must have safe-area margin');
assert.ok(pkg.scripts.build.startsWith('node scripts/generate-pwa-icons.mjs && npm test'));
assert.ok(html.includes('<link rel="manifest" href="/motyq-iq.webmanifest" />'));
assert.ok(html.includes('<link rel="apple-touch-icon" href="/icons/motyq-iq-192.png" />'));
assert.ok(html.includes('<meta name="theme-color" content="#0089cd" />'));
assert.ok(entry.includes("navigator.serviceWorker.register('/motyq-iq-sw.js',{scope:'/'})"));
assert.ok(sw.includes("event.request.mode!=='navigate'"));
assert.ok(sw.includes("event.request.method!=='GET'"));
assert.ok(sw.includes("fetch(event.request).catch"));
assert.ok(sw.includes("Cache-Control':'no-store'"));
assert.ok(!sw.includes('caches.open('),'Sensitive customer/financial data must never be persisted offline');
assert.ok(!sw.includes('cache.put('));
assert.ok(install.includes("window.addEventListener('beforeinstallprompt'"));
assert.ok(install.includes('e.preventDefault()'));
assert.ok(install.includes("window.addEventListener('appinstalled'"));
assert.ok(install.includes("window.matchMedia?.('(display-mode: standalone)')"));
assert.ok(install.includes('await event.prompt()'),'Native prompt requires operator tap');
assert.ok(ui.includes('onClick={()=>void installMotyq()}'));
assert.ok(ui.includes('Instalar Motyq IQ'));
assert.ok(ui.includes('Como instalar Motyq IQ'));
assert.ok(ui.includes('No Google Chrome do Android'));
assert.ok(ui.includes('pwaInstallInfo&&<p role="status"'));
assert.ok(ui.includes('subscribeMotyqInstall'));
assert.ok(ui.includes('p.onSave'),'Existing authenticated evaluation save must remain intact');
assert.ok(ui.includes('p.onRestoreHistory(r)'),'History still online');
console.log('Motyq IQ PWA: 192/512/maskable PNG, valid manifest, install CTA, standalone navigation, no sensitive caching passed.');
